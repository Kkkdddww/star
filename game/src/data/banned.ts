/** 공백 · 기호 지우고 소문자로 */
export const normNick = (s: string) => s.normalize('NFC').toLowerCase().replace(/[^가-힣ㄱ-ㅎㅏ-ㅣa-z0-9]/g, '');
export function hasBanned(s: string): boolean {
  const a = normNick(s), b = a.replace(/[0-9]/g, '');
  return BANNED_WORDS.some((w) => a.includes(w) || b.includes(w));
}
/** 화면에 보일 이름: 금칙어가 섞인 예전 닉네임은 가린다 */
