import type { ChoiceDef, ChoiceOption, EventType, Outcome, StatKey, Style } from '../engine/types';

type R = [string, number, Partial<Outcome>?];
const out = (r: R): Outcome => ({ text: r[0], eval: r[1], ...(r[2] ?? {}) });
/** 원칙: 반드시 성공, 작은 보상 */
const S = (label: string, desc: string, stat: StatKey, ok: R): ChoiceOption =>
  ({ key: '', label, style: '원칙', desc, stat, base: 0, sure: true, success: out(ok), fail: { text: '', eval: 0 } });
/** 확률 선택지 */
const T = (style: Style, label: string, desc: string, stat: StatKey, base: number, ok: R, ng: R, tags?: string[]): ChoiceOption =>
  ({ key: '', label, style, desc, stat, base, ...(tags ? { tags } : {}), success: out(ok), fail: out(ng) });
const E = (id: string, billets: string[], type: EventType, title: string, body: string, options: ChoiceOption[]): ChoiceDef =>
  ({ id, type, title, body, when: { billets }, options: options.map((o, i) => ({ ...o, key: 'abc'[i] })) });

